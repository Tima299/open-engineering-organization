# --------------------------------------------------------------------------- loading
def _yaml():
    try:
        import yaml  # noqa: PLC0415
    except ImportError:
        sys.exit("PyYAML is required for authoring commands: pip install -r requirements-dev.txt")
    return yaml


def load_sources():
    yaml = _yaml()

    def load(rel):
        with open(ROOT / rel, encoding="utf-8") as fh:
            return yaml.safe_load(fh)

    roles = {}
    for path in sorted((ROOT / "org" / "roles").glob("*.yaml")):
        with open(path, encoding="utf-8") as fh:
            roles[path.stem] = yaml.safe_load(fh)
    return {
        "roles": roles,
        "routing": load("org/routing.yaml"),
        "workflow": load("org/workflow.yaml"),
        "decisions": load("org/decision-rights.yaml"),
        "models": load("config/models.yaml"),
        "registry": load("third_party/registry.yaml"),
    }


def load_lock():
    if not LOCK.exists():
        sys.exit(f"{LOCK} missing: run `python3 scripts/oeo.py build`")
    return json.loads(LOCK.read_text(encoding="utf-8"))


# --------------------------------------------------------------------------- schema
def schema_errors(value, schema, path="$"):
    """Validate the JSON-Schema subset used in schemas/ (no external dependency)."""
    errs = []
    kind = schema.get("type")
    checks = {"object": dict, "array": list, "string": str, "integer": int}
    if kind and not (isinstance(value, checks[kind]) and not (kind == "integer" and isinstance(value, bool))):
        return [f"{path}: expected {kind}"]
    if "enum" in schema and value not in schema["enum"]:
        errs.append(f"{path}: {value!r} not in {schema['enum']}")
    if isinstance(value, str):
        if len(value) < schema.get("minLength", 0):
            errs.append(f"{path}: shorter than {schema['minLength']}")
        if len(value) > schema.get("maxLength", 10**9):
            errs.append(f"{path}: longer than {schema['maxLength']}")
        if "pattern" in schema and not re.search(schema["pattern"], value):
            errs.append(f"{path}: {value!r} does not match {schema['pattern']}")
    if isinstance(value, list):
        if len(value) < schema.get("minItems", 0):
            errs.append(f"{path}: needs at least {schema['minItems']} items")
        for i, item in enumerate(value):
            errs += schema_errors(item, schema.get("items", {}), f"{path}[{i}]")
    if isinstance(value, dict):
        props = schema.get("properties", {})
        errs += [f"{path}: missing '{k}'" for k in schema.get("required", []) if k not in value]
        for key, item in value.items():
            if key in props:
                errs += schema_errors(item, props[key], f"{path}.{key}")
            elif schema.get("additionalProperties") is False:
                errs.append(f"{path}: unexpected key '{key}'")
    return errs


# --------------------------------------------------------------------------- policy helpers
def effective_model(contract_routing, role_id, models, profile):
    """Apply overrides and resolve a role's tier/effort to a concrete model for a profile."""
    prof = models["profiles"][profile]
    over = dict((models.get("overrides") or {}).get("all") or {}).get(role_id, {})
    over = {**over, **((models.get("overrides") or {}).get(profile) or {}).get(role_id, {})}
    tier = over.get("preferred_model", contract_routing["preferred_model"])
    effort = over.get("effort", contract_routing["effort"])
    m = prof["tiers"][tier]
    return {"tier": tier, "effort": effort, "escalate_to": contract_routing["escalate_to"],
            "host_alias": m["host_alias"], "model_id": m["model_id"]}


def profile_name(models, requested=None):
    name = requested or os.environ.get("OEO_MODEL_PROFILE") or models["default_profile"]
    if name not in models["profiles"]:
        sys.exit(f"unknown model profile '{name}' (have: {', '.join(models['profiles'])})")
    return name


def license_verdict(spdx, policy):
    if spdx in policy["allowed"]:
        return "allowed"
    if spdx in policy["review"]:
        return "review"
    return "blocked"  # blocked list + anything unknown fails closed


# --------------------------------------------------------------------------- build
def agent_name(role):
    return role.get("agent")


def render_agent(name, description, tools, model, effort, color, body, src):
    tool_names = []
    for cap in tools:
        tool_names += [t for t in HOST_TOOLS[cap] if t not in tool_names]
    head = [
        "---",
        f"name: {name}",
        f"description: {json.dumps(description)}",
        f"tools: {', '.join(tool_names)}",
        f"model: {model}",
        f"effort: {effort}",
        f"color: {color}",
        "---",
        GENERATED.format(src=src),
        "",
    ]
    return "\n".join(head) + body.rstrip() + "\n"


def bullets(items):
    return "\n".join(f"- {i}" for i in items) if items else "- (none)"


def dedicated_agent_body(c, preamble):
    skills = [s.split(":", 1)[1] for s in c.get("relevant_skills", []) if s.startswith("oeo:")]
    method = ("\n**Method:** before starting, read " +
              ", ".join(f"`<OEO plugin root>/skills/{s}/SKILL.md`" for s in skills) +
              " and the references it names when they apply.\n") if skills else ""
    return f"""You are the **{c['title']}** of the Open Engineering Organization (OEO).

**Purpose:** {" ".join(c['purpose'].split())}
{method}
## Responsibilities
{bullets(c['responsibilities'])}

## You may decide alone
{bullets(c['decision_rights'])}

## Inputs you need (ask the orchestrator if missing)
{bullets(c['inputs'])}

## Outputs you must return
{bullets(c['outputs'])}

## Escalate instead of guessing when
{bullets(c['escalation_conditions'])}

## Your work is accepted only if
{bullets(c['acceptance_criteria'])}

{preamble}"""


def generic_agent_body(name, spec, preamble):
    tier = "Tier 2 specialist" if name == "specialist" else "Tier 3 advisor"
    return f"""You run exactly one OEO **{tier}** role contract per invocation.

1. The orchestrator's prompt names the role id and the contract path
   (`org/roles/<id>.yaml` inside the OEO plugin). Read that contract first. If it is
   missing or the role is not a {tier}, stop and say so.
   Then read the method skills it lists (`relevant_skills`) at
   `<OEO plugin root>/skills/<name>/SKILL.md`; the orchestrator gives you the plugin root.
2. Act strictly within the contract: its responsibilities, decision rights,
   escalation conditions and acceptance criteria. Produce its listed outputs.
3. If the task needs another role's decision, escalate; do not absorb that role.

{preamble}"""


def build_outputs(src, profile=None):
    """Return {relative_path: content} for every generated file."""
    models, routing = src["models"], src["routing"]
    profile = profile_name(models, profile)
    preamble = (ROOT / "org" / "agent-preamble.md").read_text(encoding="utf-8").strip()
    out = {}
    roles = {rid: doc["role"] for rid, doc in src["roles"].items()}
    lock_roles = {}
    for rid, c in roles.items():
        lock_roles[rid] = {k: c[k] for k in ("tier", "title", "execution", "model_routing")}
        for k in ("agent", "seniority", "activation"):
            if k in c:
                lock_roles[rid][k] = c[k]
        lock_roles[rid]["contract"] = f"org/roles/{rid}.yaml"
        if c["execution"] == "subagent" and c.get("agent") == rid:
            m = effective_model(c["model_routing"], rid, models, profile)
            first = re.split(r"(?<=[.!?])\s", " ".join(c["purpose"].split()), maxsplit=1)[0]
            desc = f"OEO {c['title']}: {first} Use only when the OEO router (oeo:deliver) activates this role."
            color = ROLE_COLOR.get(rid, TIER_COLOR[c["tier"]])
            out[f"agents/{rid}.md"] = render_agent(rid, desc, c["tools_and_permissions"], m["host_alias"],
                                                   m["effort"], color, dedicated_agent_body(c, preamble),
                                                   f"org/roles/{rid}.yaml")
    for name, spec in routing["generic_agents"].items():
        alias = models["profiles"][profile]["tiers"][spec["preferred_model"]]["host_alias"]
        out[f"agents/{name}.md"] = render_agent(name, spec["description"], spec["tools"], alias, spec["effort"],
                                                "orange", generic_agent_body(name, spec, preamble),
                                                "org/routing.yaml")
    lock = {
        "generated_by": "scripts/oeo.py build",
        "roles": lock_roles,
        "routing": routing,
        "workflow": {"stages": src["workflow"]["stages"], "gates": src["workflow"]["gates"]},
        "decisions": src["decisions"]["categories"],
        "models": models,
    }
    out["org/org.lock.json"] = json.dumps(lock, indent=1, sort_keys=True) + "\n"
    out["docs/roles.md"] = render_role_catalog(roles, models, profile)
    out["THIRD_PARTY.md"] = render_third_party(src["registry"], routing["licenses"])
    return out


def render_third_party(registry, policy):
    rows = ["# Third-party resources", "", GENERATED.format(src="third_party/registry.yaml"), "",
            "OEO bundles **no** third-party skill files. The resources below were evaluated and are",
            "referenced as optional adapters: install them yourself through the upstream installer,",
            "under the upstream license. OEO's router suggests them only when they are already",
            "installed in your session. Runtime: OEO has no third-party runtime dependencies;",
            "contributors need PyYAML (MIT), see `requirements-dev.txt` and `sbom.cdx.json`.", "",
            "| Resource | License | Revision | Status | Why / limits |", "|---|---|---|---|---|"]
    for r in registry["resources"]:
        rev = r["revision"] if r["revision"] == "UNVERIFIED" else f"`{r['revision'][:12]}`"
        rows.append(f"| [{r['name']}]({r['upstream_url']}) ({r['maintainer']}) | "
                    f"[{r['license_spdx']}]({r['license_evidence_url']}) ({license_verdict(r['license_spdx'], policy)}) | "
                    f"{rev} | {r['status']}, {r['accessed']} | {r['rationale']} *Limits:* {r['limitations']} |")
    adopted = [r for r in registry["resources"] if r.get("adopted_ideas")]
    if adopted:
        rows += ["", "## Ideas adapted into OEO", "",
                 "Re-expressed in OEO's own words (no upstream text is copied). Credit to the upstream authors:", ""]
        for r in adopted:
            rows.append(f"- **{r['name']}** ({r['license_spdx']}): " + "; ".join(r["adopted_ideas"]))
    rows += ["", "Install commands, environments and verification notes: `third_party/registry.yaml`."]
    return "\n".join(rows) + "\n"


def render_role_catalog(roles, models, profile):
    rows = ["# Role catalog", "", GENERATED.format(src="org/roles/*.yaml"), "",
            f"Model column uses the `{profile}` profile of `config/models.yaml`.", "",
            "| Tier | Role | Runs as | Model / effort | Activated by |", "|---|---|---|---|---|"]
    for rid, c in sorted(roles.items(), key=lambda kv: (kv[1]["tier"], kv[0])):
        m = effective_model(c["model_routing"], rid, models, profile)
        runs = c["execution"] + (f" (`oeo:{c['agent']}`)" if c.get("agent") and c["execution"] == "subagent" else "")
        act = c.get("activation", {})
        if c["tier"] == 1:
            how = "class core set"
        elif "delegated_by" in act:
            how = f"delegated by {act['delegated_by']}"
        else:
            how = ", ".join(act.get("domains", []) + act.get("triggers", []))
            if act.get("unless"):
                how += f" (unless {', '.join(act['unless'])})"
        rows.append(f"| {c['tier']} | [{c['title']}](../org/roles/{rid}.yaml) | {runs} | "
                    f"{m['tier']} → {m['model_id']} / {m['effort']} | {how} |")
    return "\n".join(rows) + "\n"


def cmd_build(args):
    src = load_sources()
    errors = validate_sources(src)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit("build aborted: fix validation errors first")
    outputs = build_outputs(src, args.profile)
    stale = []
    for rel, content in outputs.items():
        path = ROOT / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(rel)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    expected = {p for p in outputs if p.startswith("agents/")}
    orphans = sorted(str(p.relative_to(ROOT)) for p in (ROOT / "agents").glob("*.md")
                     if str(p.relative_to(ROOT)) not in expected)
    if args.check:
        if stale or orphans:
            sys.exit("generated files out of date: " + ", ".join(stale + orphans) +
                     "\nrun `python3 scripts/oeo.py build`")
        print(f"build check OK ({len(outputs)} generated files up to date)")
    else:
        for p in orphans:
            (ROOT / p).unlink()
        print(f"wrote {len(stale)} file(s), removed {len(orphans)} orphan(s); {len(outputs)} generated in total")


# --------------------------------------------------------------------------- validate
PROVIDER_NAMES = re.compile(r"\b(claude-[a-z0-9-]+|gpt-[0-9a-z.-]+|gemini[-a-z0-9.]*|sonnet|opus|haiku)\b", re.I)


def validate_sources(src):
    errs = []
    schema = json.loads((ROOT / "schemas" / "role.schema.json").read_text(encoding="utf-8"))
    routing, workflow, decisions, models = src["routing"], src["workflow"], src["decisions"], src["models"]
    role_ids = set(src["roles"])
    skills = {f"oeo:{p.parent.name}" for p in (ROOT / "skills").glob("*/SKILL.md")}
    adapters = {r["id"] for r in src["registry"].get("resources", [])}
    vocab = set(routing["types"]) | set(routing["domains"]) | set(routing["signals"])
    generic = set(routing["generic_agents"])

    for rid, doc in src["roles"].items():
        where = f"org/roles/{rid}.yaml"
        errs += [f"{where}: {e}" for e in schema_errors(doc, schema)]
        if not isinstance(doc, dict) or "role" not in doc or not isinstance(doc["role"], dict):
            continue
        c = doc["role"]
        if c.get("id") != rid:
            errs.append(f"{where}: id '{c.get('id')}' must match file name")
        for field in ("consults", "informs"):
            for ref in c.get(field, []):
                if ref not in role_ids or ref == rid:
                    errs.append(f"{where}: {field} references unknown or self role '{ref}'")
        for skill in c.get("relevant_skills", []):
            if skill not in skills and skill not in adapters:
                errs.append(f"{where}: relevant skill '{skill}' is neither an oeo skill nor a registered adapter")
        agent, execution, act = c.get("agent"), c.get("execution"), c.get("activation", {})
        if execution == "subagent" and not agent:
            errs.append(f"{where}: subagent roles must name an agent")
        if agent and agent != rid and agent not in generic:
            errs.append(f"{where}: agent '{agent}' must be the role id (dedicated) or a generic agent {sorted(generic)}")
        elif agent in generic:
            missing = sorted(set(c.get("tools_and_permissions", [])) - set(routing["generic_agents"][agent]["tools"]))
            if missing:
                errs.append(f"{where}: generic agent '{agent}' lacks tools {missing} that this contract needs")
        tier = c.get("tier")
        if tier == 1 and act:
            errs.append(f"{where}: Tier 1 roles are activated by class, not by 'activation'")
        if tier == 2 and not (act.get("domains") or act.get("delegated_by")):
            errs.append(f"{where}: Tier 2 roles need activation.domains or activation.delegated_by")
        if tier == 3 and not act.get("triggers"):
            errs.append(f"{where}: Tier 3 roles need activation.triggers (explicit trigger conditions)")
        for key in act.get("domains", []) + act.get("unless", []) + [p for t in act.get("triggers", []) for p in t.split("+")]:
            if key not in vocab:
                errs.append(f"{where}: activation key '{key}' is not a type, domain or signal in org/routing.yaml")
        if act.get("delegated_by") and act["delegated_by"] not in role_ids:
            errs.append(f"{where}: delegated_by '{act['delegated_by']}' is not a role")
        text = (ROOT / where).read_text(encoding="utf-8")
        hit = PROVIDER_NAMES.search(text)
        if hit:
            errs.append(f"{where}: provider model name '{hit.group(0)}' in a role contract (use a tier; anti-pattern 7)")

    stage_ids = {s["id"] for s in workflow["stages"]}
    for s in workflow["stages"]:
        if s["owner"] not in role_ids:
            errs.append(f"org/workflow.yaml: stage '{s['id']}' owner '{s['owner']}' is not a role")
    for cls, cfg in routing["classes"].items():
        w = f"org/routing.yaml classes.{cls}"
        errs += [f"{w}: unknown role '{r}'" for r in cfg["roles"] if r not in role_ids]
        errs += [f"{w}: unknown stage '{s}'" for s in cfg["stages"] if s not in stage_ids]
        errs += [f"{w}: unknown gate '{g}'" for g in cfg["gates"] if g not in workflow["gates"]]
        errs += [f"{w}: bad mode '{m}'" for m in cfg["roles"].values() if m not in ("human", "orchestrator", "checklist", "subagent")]
        for r, m in cfg["roles"].items():
            if m == "subagent" and r in src["roles"] and not src["roles"][r]["role"].get("agent"):
                errs.append(f"{w}: '{r}' runs as subagent but its contract names no agent")
    for key, rule in routing.get("fact_rules", {}).items():
        if key not in vocab:
            errs.append(f"org/routing.yaml fact_rules: '{key}' is not a type, domain or signal")
        errs += [f"org/routing.yaml fact_rules.{key}: unknown gate '{g}'" for g in rule.get("gates", []) if g not in workflow["gates"]]
        errs += [f"org/routing.yaml fact_rules.{key}: unknown stage '{s}'"
                 for s in rule.get("stages", []) + rule.get("remove_stages", []) if s not in stage_ids]
        errs += [f"org/routing.yaml fact_rules.{key}: unknown gate '{g}'" for g in rule.get("remove_gates", []) if g not in workflow["gates"]]
        errs += [f"org/routing.yaml fact_rules.{key}: unknown role '{r}'" for r in rule.get("remove_roles", []) if r not in role_ids]
    for rule in routing["classification"]:
        if rule["class"] not in routing["classes"]:
            errs.append(f"org/routing.yaml: rule '{rule['rule']}' targets unknown class")
    for cls, dev in routing["developer_by_class"].items():
        if dev and dev not in role_ids:
            errs.append(f"org/routing.yaml developer_by_class.{cls}: unknown role '{dev}'")
    sk = routing["skills"]
    for group in ("by_class", "by_domain", "by_signal", "by_type"):
        for key, names in sk.get(group, {}).items():
            errs += [f"org/routing.yaml skills.{group}.{key}: unknown skill '{n}'" for n in names if n not in skills]
    for group, table in sk["adapters"].items():
        for key, names in table.items():
            errs += [f"org/routing.yaml skills.adapters.{group}.{key}: '{n}' not in third_party/registry.yaml"
                     for n in names if n not in adapters]

    groups = {k: set(v) for k, v in decisions["groups"].items()}
    seen = set()
    for cat in decisions["categories"]:
        w = f"org/decision-rights.yaml {cat['id']}"
        if cat["id"] in seen:
            errs.append(f"{w}: duplicate category")
        seen.add(cat["id"])
        refs = [cat["decides"], cat.get("fallback")] + cat["consulted"] + cat["informed"] + [v["role"] for v in cat["veto"]]
        for ref in filter(None, refs):
            if ref.startswith("@"):
                if ref[1:] not in groups:
                    errs.append(f"{w}: unknown group '{ref}'")
            elif ref not in role_ids:
                errs.append(f"{w}: unknown role '{ref}'")
        if any(not v.get("grounds") for v in cat["veto"]):
            errs.append(f"{w}: every veto needs written grounds")
    for g, members in groups.items():
        errs += [f"org/decision-rights.yaml groups.{g}: unknown role '{m}'" for m in members if m not in role_ids]

    for name, prof in models["profiles"].items():
        missing = [t for t in TIERS if t not in prof.get("tiers", {})]
        if missing:
            errs.append(f"config/models.yaml profile '{name}': missing tiers {missing}")
    for scope, table in (models.get("overrides") or {}).items():
        if scope != "all" and scope not in models["profiles"]:
            errs.append(f"config/models.yaml overrides: scope '{scope}' is neither 'all' nor a profile")
        for rid, over in (table or {}).items():
            if rid not in role_ids:
                errs.append(f"config/models.yaml overrides.{scope}: unknown role '{rid}'")
            if over.get("preferred_model", "standard") not in TIERS or over.get("effort", "low") not in EFFORTS:
                errs.append(f"config/models.yaml overrides.{scope}.{rid}: bad tier or effort")

    errs += validate_registry(src["registry"], routing["licenses"])
    errs += validate_sbom(routing["licenses"])
    errs += validate_links()
    return errs


def validate_sbom(policy):
    """sbom.cdx.json must list every pinned dev dependency with an allowed license."""
    errs = []
    sbom = json.loads((ROOT / "sbom.cdx.json").read_text(encoding="utf-8"))
    plugin = json.loads((ROOT / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8"))
    if sbom["metadata"]["component"]["version"] != plugin["version"]:
        errs.append("sbom.cdx.json: metadata version differs from .claude-plugin/plugin.json")
    listed = {(c["name"].lower(), c["version"]): c for c in sbom.get("components", [])}
    pins = re.findall(r"^([A-Za-z0-9_.-]+)==([^\s\\]+)", (ROOT / "requirements-dev.txt").read_text(encoding="utf-8"), re.M)
    for name, version in pins:
        comp = listed.get((name.lower(), version))
        if not comp:
            errs.append(f"sbom.cdx.json: {name}=={version} from requirements-dev.txt is missing")
            continue
        for lic in comp.get("licenses", []):
            if license_verdict(lic["license"]["id"], policy) != "allowed":
                errs.append(f"sbom.cdx.json: {name} license {lic['license']['id']} fails the legal gate")
    return errs


REGISTRY_FIELDS = ("id", "name", "upstream_url", "maintainer", "license_spdx", "revision", "install",
                   "environments", "limitations", "rationale", "distribution", "status", "accessed")


def validate_registry(registry, policy):
    errs = []
    for r in registry.get("resources", []):
        w = f"third_party/registry.yaml {r.get('id', '?')}"
        errs += [f"{w}: missing '{f}'" for f in REGISTRY_FIELDS if f not in r]
        if r.get("distribution") not in ("reference-only", "vendored", "dependency"):
            errs.append(f"{w}: distribution must be reference-only, vendored or dependency")
        verdict = license_verdict(r.get("license_spdx"), policy)
        if r.get("distribution") != "reference-only" and verdict != "allowed":
            errs.append(f"{w}: {verdict} license '{r.get('license_spdx')}' cannot be {r.get('distribution')} (legal gate)")
        if r.get("status") == "verified" and (not r.get("license_evidence_url") or r.get("revision") == "UNVERIFIED"):
            errs.append(f"{w}: 'verified' needs license_evidence_url and a confirmed revision (else partially-verified)")
    return errs


LINK = re.compile(r"\]\((?!https?://|mailto:|#)([^)\s]+)\)")


def validate_links():
    errs = []
    for md in ROOT.rglob("*.md"):
        rel = md.relative_to(ROOT)
        if rel.parts[0] in (".git", "node_modules") or "results" in rel.parts:
            continue
        for target in LINK.findall(md.read_text(encoding="utf-8")):
            path = target.split("#", 1)[0]
            if path and not (md.parent / path).exists():
                errs.append(f"{rel}: broken relative link '{target}'")
    return errs


def cmd_validate(args):
    src = load_sources()
    errors = validate_sources(src)
    if not errors:
        outputs = build_outputs(src)
        stale = [p for p, c in outputs.items()
                 if not (ROOT / p).exists() or (ROOT / p).read_text(encoding="utf-8") != c]
        errors += [f"{p}: out of date, run `python3 scripts/oeo.py build`" for p in stale]
    if errors:
        print("\n".join(f"FAIL {e}" for e in errors))
        sys.exit(f"{len(errors)} validation error(s)")
    print(f"OK: {len(src['roles'])} role contracts, {len(src['decisions']['categories'])} decision categories, "
          f"{len(src['registry'].get('resources', []))} third-party entries, links and generated files valid")


