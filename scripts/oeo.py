def _read_jsonl(path):
    if not path.exists():
        return []
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return rows


def cmd_cost(args):
    base = project_dir() / ".oeo"
    usage, plans = _read_jsonl(base / "finops.jsonl"), _read_jsonl(base / "activation-log.jsonl")
    if args.session:
        usage = [u for u in usage if u.get("session_id") == args.session]
        plans = [p for p in plans if p.get("session") == args.session]
    if not usage and not plans:
        print(f"No FinOps data in {base} (logs appear after `oeo route --log` and subagent runs).")
        return
    per_agent = {}
    for u in usage:
        key = u.get("agent_type") or "unknown"
        agg = per_agent.setdefault(key, {"runs": 0, "input": 0, "output": 0, "cache_read": 0, "cache_write": 0})
        agg["runs"] += 1
        for k in ("input", "output", "cache_read", "cache_write"):
            agg[k] += u.get(k + "_tokens", 0)
    estimates = {}
    for p in plans:
        for r in p.get("roles", []):
            if r.get("agent"):
                estimates[r["agent"].split(":")[-1]] = estimates.get(r["agent"].split(":")[-1], 0) + (r.get("estimate_tokens") or 0)
    print(f"{'agent':<34}{'runs':>5}{'input':>11}{'output':>10}{'cache_rd':>11}{'estimate':>11}  flag")
    total = 0
    for agent, a in sorted(per_agent.items()):
        actual = a["input"] + a["output"] + a["cache_write"]
        total += actual
        est = estimates.get(agent.split(":")[-1])
        flag = "OVER ESTIMATE" if est and actual > est else ("unplanned" if est is None and agent.split(":")[-1] not in ("", "unknown") and plans else "")
        print(f"{agent:<34}{a['runs']:>5}{a['input']:>11,}{a['output']:>10,}{a['cache_read']:>11,}"
              f"{(est or 0):>11,}  {flag}")
    budget = sum(p.get("budget_tokens", 0) for p in plans)
    planned = sum(p.get("estimate_tokens", 0) for p in plans)
    print(f"\nTotal subagent tokens (input+output+cache writes): {total:,}; planned {planned:,}; class budget {budget:,}")
    if budget and total > budget:
        print("BUDGET EXCEEDED: record a justification in .oeo/decisions.md (FinOps guardrail).")
    invoked = len(per_agent)
    print(f"Coordination: {invoked} distinct agent types, {sum(a['runs'] for a in per_agent.values())} runs; "
          "cache reads are reported but excluded from the budget total.")


