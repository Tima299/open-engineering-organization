def _triggered(role, facts):
    act = role.get("activation", {})
    if any(u in facts for u in act.get("unless", [])):
        return None
    for trig in act.get("triggers", []):
        if all(p in facts for p in trig.split("+")):
            return trig
    return None


def _matches(when, ctx):
    checks = {
        "types_any": lambda v: ctx["type"] in v,
        "risky_domain": lambda v: ctx["risky"] == v,
        "signals_any": lambda v: bool(ctx["facts"] & set(v)),
        "files_gt": lambda v: ctx["files"] is not None and ctx["files"] > v,
        "files_lte": lambda v: ctx["files"] is not None and ctx["files"] <= v,
        "lines_lte": lambda v: ctx["lines"] is not None and ctx["lines"] <= v,
        "no_triggers": lambda v: (not ctx["triggers"]) == v,
    }
    return all(checks[k](v) for k, v in when.items())


def route(lock, task_type, touches=(), signals=(), files=None, lines=None, profile=None):
    """Pure function: inputs -> activation plan (dict). No I/O."""
    routing, roles, models = lock["routing"], lock["roles"], lock["models"]
    unknown = ([f"type '{task_type}'"] if task_type not in routing["types"] else []) + \
              [f"domain '{d}'" for d in touches if d not in routing["domains"]] + \
              [f"signal '{s}'" for s in signals if s not in routing["signals"]]
    if unknown:
        raise ValueError("unknown " + ", ".join(unknown) + " (see org/routing.yaml)")
    profile = profile_name(models, profile)
    facts = set(signals) | set(touches) | {task_type}
    tier3 = {rid: r for rid, r in roles.items() if r["tier"] == 3}
    pre_triggers = {rid: t for rid, r in tier3.items() if (t := _triggered(r, facts))}
    ctx = {"type": task_type, "facts": facts, "files": files, "lines": lines, "triggers": pre_triggers,
           "risky": any(routing["domains"][d]["risky"] for d in touches)}
    rule = next(r for r in routing["classification"] if _matches(r["when"], ctx))
    cls, cfg = rule["class"], routing["classes"][rule["class"]]
    facts |= set(cfg.get("derive_signals", []))

    active = {}
    for rid, mode in cfg["roles"].items():
        active[rid] = {"mode": mode, "reason": f"class {cls} core"}
    if cfg["tier2"]:
        for rid, r in sorted(roles.items()):
            hit = sorted(facts & set(r.get("activation", {}).get("domains", []))) if r["tier"] == 2 else []
            if hit:
                active[rid] = {"mode": r["execution"], "reason": f"domain: {', '.join(hit)}"}
    if cfg["tier3"]:
        for rid, r in sorted(tier3.items()):
            trig = _triggered(r, facts)
            if trig:
                active[rid] = {"mode": r["execution"], "reason": f"trigger: {trig}"}

    if cls != "A":
        for key in sorted(facts):
            for rid in routing.get("fact_rules", {}).get(key, {}).get("remove_roles", []):
                active.pop(rid, None)

    budgets = models["budgets"]
    estimate = 0
    plan_roles = []
    for rid, a in active.items():
        r = roles[rid]
        entry = {"id": rid, "tier": r["tier"], "title": r["title"], **a, "contract": r["contract"]}
        if a["mode"] == "subagent":
            m = effective_model(r["model_routing"], rid, models, profile)
            entry.update(agent=f"oeo:{r['agent']}", model=m["host_alias"], model_id=m["model_id"],
                         effort=m["effort"], escalate_to=m["escalate_to"],
                         estimate_tokens=budgets["per_invocation_tokens"][m["effort"]])
            estimate += entry["estimate_tokens"]
        plan_roles.append(entry)
    plan_roles.sort(key=lambda e: (e["tier"], e["id"]))

    sk = routing["skills"]
    skills = list(sk["by_class"].get(cls, []))
    for s in sk.get("by_type", {}).get(task_type, []) + \
            [s for key in sorted(facts) for s in sk["by_domain"].get(key, []) + sk["by_signal"].get(key, [])]:
        if s not in skills:
            skills.append(s)
    adapters = []
    if cls != "A":
        ad = sk["adapters"]
        for a in [a for key in sorted(touches) for a in ad.get("by_domain", {}).get(key, [])] + \
                ad.get("by_type", {}).get(task_type, []) + \
                [a for key in sorted(facts) for a in ad.get("by_signal", {}).get(key, [])]:
            if a not in adapters:
                adapters.append(a)
    gates, stages = list(cfg["gates"]), list(cfg["stages"])
    if cls != "A":
        for key in sorted(facts):
            rule_ = routing.get("fact_rules", {}).get(key, {})
            gates += [g for g in rule_.get("gates", []) if g not in gates]
            stages += [s for s in rule_.get("stages", []) if s not in stages]
            gates = [g for g in gates if g not in rule_.get("remove_gates", [])]
            stages = [s for s in stages if s not in rule_.get("remove_stages", [])]
    order = [s["id"] for s in lock["workflow"]["stages"]]
    stages.sort(key=order.index)
    stage_names = {s["id"]: f"{s['n']} {s['name']}" for s in lock["workflow"]["stages"]}
    return {
        "class": cls, "class_name": cfg["name"], "rule": rule["rule"], "profile": profile,
        "inputs": {"type": task_type, "touches": sorted(touches), "signals": sorted(signals), "files": files, "lines": lines},
        "stages": [stage_names[s] for s in stages],
        "roles": plan_roles,
        "not_activated": sorted(set(roles) - set(active)),
        "skills": skills, "optional_adapters": adapters,
        "gates": [{"id": g, "check": lock["workflow"]["gates"][g]} for g in gates],
        "retry_budget": routing["retry_budget"],
        "estimate_tokens": estimate, "budget_tokens": budgets["per_class_tokens"][cls],
    }


def format_plan(plan):
    out = [f"OEO triage: Class {plan['class']} ({plan['class_name']})  rule={plan['rule']}  profile={plan['profile']}",
           "Stages: " + " -> ".join(plan["stages"]),
           f"Roles ({len(plan['roles'])} activated, {len(plan['not_activated'])} not activated):"]
    for r in plan["roles"]:
        run = f"{r['agent']} [{r['model']}/{r['effort']}]" if r["mode"] == "subagent" else r["mode"]
        out.append(f"  T{r['tier']} {r['id']:<26} {run:<44} {r['reason']}")
    out.append("Skills: " + ", ".join(plan["skills"]))
    if plan["optional_adapters"]:
        out.append("Optional adapters (only if already installed): " + ", ".join(plan["optional_adapters"]))
    out.append("Gates: " + ", ".join(g["id"] for g in plan["gates"]))
    out.append(f"Budget: est {plan['estimate_tokens']:,} subagent tokens of {plan['budget_tokens']:,} "
               f"(class {plan['class']}); retry budget {plan['retry_budget']} per gate")
    return "\n".join(out)


def project_dir():
    return Path(os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd())


def cmd_route(args):
    split = lambda s: [x.strip() for x in s.split(",") if x.strip()] if s else []  # noqa: E731
    try:
        plan = route(load_lock(), args.type, split(args.touches), split(args.signals), args.files, args.lines, args.profile)
    except ValueError as exc:
        sys.exit(str(exc))
    print(json.dumps(plan, indent=1) if args.json else format_plan(plan))
    if args.log:
        log_dir = project_dir() / ".oeo"
        log_dir.mkdir(exist_ok=True)
        entry = {"ts": _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds"), "session": args.session,
                 "summary": args.summary, "class": plan["class"], "rule": plan["rule"], "inputs": plan["inputs"],
                 "roles": [{k: r.get(k) for k in ("id", "mode", "reason", "agent", "model", "effort", "estimate_tokens")}
                           for r in plan["roles"]],
                 "estimate_tokens": plan["estimate_tokens"], "budget_tokens": plan["budget_tokens"]}
        with open(log_dir / "activation-log.jsonl", "a", encoding="utf-8") as fh:
            fh.write(json.dumps(entry) + "\n")
        print(f"(logged to {log_dir / 'activation-log.jsonl'})", file=sys.stderr)


